#!/usr/bin/env python3
"""Builds www/fonts-ar.css + www/fonts/*.woff2 from @fontsource packages (Arabic + Latin subsets, weights 400/700).
A missing package or file only prints a warning; that font then falls back to the system font."""
import re, shutil, pathlib
NM = pathlib.Path('node_modules/@fontsource')
OUT = pathlib.Path('www'); FD = OUT / 'fonts'; FD.mkdir(parents=True, exist_ok=True)
SPEC = [  # (package, [css family names that should map to it])
 ('cairo', ['Cairo']),
 ('amiri', ['Amiri', 'Sakkal Majalla', 'Arabic Typesetting']),
 ('tajawal', ['Tajawal']),
 ('almarai', ['Almarai']),
 ('noto-naskh-arabic', ['Noto Naskh Arabic', 'Traditional Arabic', 'Simplified Arabic']),
 ('noto-kufi-arabic', ['Noto Kufi Arabic']),
]
out = ['/* generated by scripts/arabic-fonts.py */\n']; ok = 0
for pkg, names in SPEC:
    got = False
    for sub in ('arabic', 'latin'):
        for w in (400, 700):
            f = NM / pkg / f'{sub}-{w}.css'
            if not f.exists():
                print(f'::warning::font css missing: {f}'); continue
            for blk in re.findall(r'@font-face\s*\{.*?\}', f.read_text(encoding='utf8'), re.S):
                m = re.search(r'url\(\.?/?files/([^)]+?\.woff2)\)', blk)
                if not m: continue
                src = NM / pkg / 'files' / m.group(1)
                if not src.exists(): print(f'::warning::font file missing: {src}'); continue
                shutil.copy(src, FD / m.group(1))
                blk = re.sub(r"src:[^;}]*", f"src:url(fonts/{m.group(1)}) format('woff2')", blk, count=1)
                for n in names:
                    out.append(re.sub(r"font-family:[^;]*", f"font-family:'{n}'", blk, count=1) + '\n')
                got = True
    ok += got
    if not got: print(f'::warning::no Arabic font files for {pkg}')
(OUT / 'fonts-ar.css').write_text(''.join(out), encoding='utf8')
print(f'arabic fonts: {ok}/{len(SPEC)} packages bundled')
